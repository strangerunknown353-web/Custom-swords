#!/usr/bin/env node
/**
 * Generates `SWORD_CATALOG.md` from the sword definitions.
 *
 * The catalogue is the player-facing and designer-facing reference, and it will
 * eventually list 20-25 swords. Hand-maintaining it would guarantee that a
 * balance tweak in a definition and the number in the docs eventually disagree,
 * so it is derived from the same source of truth the game loads.
 *
 * Usage: node tools/catalog.mjs [--check]
 *   --check  Fail (exit 1) instead of writing, if the catalogue is stale.
 */

import fs from 'node:fs';
import path from 'node:path';

import { PATHS, MODULES } from './lib/project.mjs';

const CHECK_ONLY = process.argv.includes('--check');
const OUTPUT = path.join(PATHS.root, 'SWORD_CATALOG.md');

const { SWORDS } = await import(MODULES.swords);
const { ABILITIES } = await import(MODULES.abilities);
const { describeAll } = await import(MODULES.swordStats);
const { ACTIVATION_LABELS } = await import(`file://${path.join(PATHS.coreDir, 'activation.js')}`);
const { localNameOf } = await import(`file://${path.join(PATHS.coreDir, 'identifiers.js')}`);
const { resolvePresentation } = await import(`file://${path.join(PATHS.coreDir, 'visual_profiles.js')}`);

/** @param {any} sword @returns {string[]} The distinct visual profiles its bindings use. */
function profilesOf(sword) {
    return [...new Set(sword.abilities.map((b) => b.visual).filter(Boolean))];
}

/** @param {string} id */
const abilityName = (id) => ABILITIES.find((a) => a.id === id)?.name ?? id;
/** The name a player sees: the binding's own label, else the ability's. */
const bindingName = (binding) => binding.label ?? abilityName(binding.abilityId);

/**
 * @param {any} sword
 * @param {'use' | 'sneak_use' | 'attack' | 'sneak_attack'} activation
 */
const bindingFor = (sword, activation) => sword.abilities.find((b) => b.activation === activation);

/** @param {any} binding */
function describeBinding(binding) {
    if (binding === undefined) return '—';
    const targeting = binding.targeting ?? { type: 'self' };
    const range = targeting.range === undefined ? '' : ` r${targeting.range}`;
    const effects = (binding.effects ?? []).map((e) => e.effect).join(', ');
    return (
        `**${bindingName(binding)}** · ${targeting.type}${range}` +
        `${effects ? ` · ${effects}` : ''}`
    );
}

const shipped = SWORDS.filter((s) => s.isTestItem !== true);
const diagnostics = SWORDS.filter((s) => s.isTestItem === true);
const described = new Map(describeAll(SWORDS).map((d) => [d.id, d]));

const lines = [
    '# Sword catalogue',
    '',
    '> Generated by `tools/catalog.mjs` from `packs/CustomSwordsBP/scripts/swords/`.',
    '> Do not edit by hand — edit the definitions and run `npm run catalog`.',
    '',
    `**${shipped.length} of a planned 20–25 swords.** Diagnostic items are listed separately and`,
    'are not part of the collection.',
    '',
    '## Summary',
    '',
    '| Sword | Rarity | Melee | Durability | Active | Cooldown | Passive |',
    '|---|---|---:|---:|---|---:|---|',
];

for (const sword of shipped) {
    const d = described.get(sword.id);
    const active = bindingFor(sword, 'use');
    const passive = bindingFor(sword, 'attack');
    lines.push(
        `| ${sword.name} | ${d.rarityLabel} | ${d.stats.meleeDamage} | ${d.stats.durability} ` +
            `| ${active === undefined ? '—' : bindingName(active)} ` +
            `| ${active === undefined ? '—' : `${(active.cooldownTicks ?? 0) / 20}s`} ` +
            `| ${passive === undefined ? '—' : bindingName(passive)} |`,
    );
}

lines.push('', '## Swords', '');

for (const sword of shipped) {
    const d = described.get(sword.id);
    lines.push(`### ${sword.name}`, '');
    lines.push(`*${sword.description}*`, '');
    lines.push('| | |', '|---|---|');
    lines.push(`| **Identifier** | \`${sword.id}\` |`);
    lines.push(`| **Rarity** | ${d.rarityLabel} |`);
    lines.push(`| **Melee damage** | ${d.stats.meleeDamage} (component value ${d.stats.attackDamage}) |`);
    lines.push(`| **Durability** | ${d.stats.durability} |`);
    lines.push(
        `| **Enchantable** | ${d.stats.enchantable ? `yes (value ${d.stats.enchantValue})` : 'no'} |`,
    );
    lines.push(`| **Repairs with** | ${d.stats.repairItems.join(', ') || '—'} |`);
    if (sword.item.swingDuration !== undefined) {
        lines.push(`| **Swing** | ${sword.item.swingDuration}s |`);
    }
    lines.push(`| **Visual profile** | ${profilesOf(sword).join(', ') || '—'} |`);
    lines.push(`| **Texture** | \`art/swords/${sword.texture ?? localNameOf(sword.id)}.json\` — authored, passes the texture standard |`);
    lines.push('');

    lines.push('**Crafting** — shaped, crafting table, yields 1:', '');
    lines.push('```');
    for (const row of sword.recipe.pattern) lines.push(`  ${[...row].join(' ')}`);
    lines.push('');
    for (const [ch, item] of Object.entries(sword.recipe.key)) {
        lines.push(`  ${ch} = ${item.replace('minecraft:', '')}`);
    }
    lines.push('```', '');

    lines.push('| Activation | Ability | Cooldown | Targets | Details | Particles | Sounds |');
    lines.push('|---|---|---:|---|---|---|---|');
    for (const binding of sword.abilities) {
        const targeting = binding.targeting ?? { type: 'self' };
        const details = [];
        const damage = describeDamage(binding.params ?? {}, sword);
        if (damage !== undefined) details.push(damage);
        if (binding.knockback?.horizontal) {
            details.push(`knockback ${binding.knockback.horizontal}${binding.knockback.mode === 'forward' ? ' (wave)' : ''}`);
        }
        if (binding.params?.igniteSeconds) details.push(`ignite ${binding.params.igniteSeconds}s`);
        for (const effect of binding.effects ?? []) {
            details.push(`${effect.effect} ${(effect.durationTicks / 20).toFixed(1)}s`);
        }
        if (binding.restrictions !== undefined) details.push('restricted');
        const { particles, sounds } = resolvePresentation(binding);
        const particleNames = particles.map((p) => p.id.replace('minecraft:', '')).join(', ') || '—';
        const soundNames = Object.entries(sounds)
            .map(([slot, value]) => `${slot}: ${typeof value === 'string' ? value : value?.id}`)
            .join(', ') || '—';
        lines.push(
            `| ${ACTIVATION_LABELS[binding.activation]} | ${bindingName(binding)} ` +
                `| ${(binding.cooldownTicks ?? 0) / 20}s ` +
                `| ${(binding.allowedTargets ?? ['any']).join(', ')} ` +
                `| ${details.join(' · ') || '—'} ` +
                `| ${particleNames} | ${soundNames} |`,
        );
    }
    lines.push('');
}

if (diagnostics.length > 0) {
    lines.push('## Diagnostic items', '', 'Not part of the collection; used to verify the framework.', '');
    for (const sword of diagnostics) {
        const d = described.get(sword.id);
        lines.push(
            `- **${sword.name}** (\`${sword.id}\`) — ${d.stats.meleeDamage} melee, ` +
                `${d.stats.durability} durability, ${sword.abilities.length} bindings.`,
        );
    }
    lines.push('');
}

lines.push('## Abilities', '');
lines.push('| Ability | Used by | Behaviour |');
lines.push('|---|---|---|');
for (const ability of ABILITIES) {
    const users = SWORDS.filter((s) => s.abilities.some((b) => b.abilityId === ability.id)).map((s) => s.name);
    lines.push(`| **${ability.name}** | ${users.join(', ') || '—'} | ${ability.description ?? ''} |`);
}
lines.push('');

const content = `${lines.join('\n')}`;
const existing = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';

if (existing === content) {
    console.log('catalog: up to date.');
} else if (CHECK_ONLY) {
    console.error("catalog --check: SWORD_CATALOG.md is stale. Run 'npm run catalog'.");
    process.exitCode = 1;
} else {
    fs.writeFileSync(OUTPUT, content);
    console.log(`catalog: wrote SWORD_CATALOG.md (${shipped.length} sword(s), ${ABILITIES.length} abilities).`);
}

/**
 * A binding's damage, in whatever shape the ability expresses it.
 *
 * Reporting only a flat `damage` understated every ability whose output scales:
 * Void Rift declares `nearDamage` + `reachBonus` and would have published no
 * damage at all, and Shadow Edge's `damage: 1` hid the 7 it actually deals
 * inside its window. The catalogue is the roster players read, so it reports the
 * range rather than the floor.
 *
 * @param {Record<string, any>} params
 * @param {any} sword The owning sword, so a charge-fed active can find the
 *   ceiling declared by the passive that fills its meter.
 * @returns {string | undefined}
 */
function describeDamage(params, sword) {
    const round = (n) => String(Math.round(n * 10) / 10);

    // Abilities whose damage ramps over a world or spatial condition. Each pairs
    // a floor with a bonus under its own names, so the catalogue reports the
    // range rather than silently publishing nothing.
    for (const [floor, bonus, why] of [
        ['nearDamage', 'reachBonus', 'scales with reach'],
        ['nightDamage', 'sunBonus', 'scales with daylight'],
        ['groundDamage', 'heightBonus', 'scales with the target’s height'],
    ]) {
        if (typeof params[floor] !== 'number') continue;
        const top = params[floor] + (params[bonus] ?? 0);
        return top > params[floor]
            ? `${round(params[floor])}-${round(top)} ability damage (${why})`
            : `${round(params[floor])} ability damage`;
    }

    if (typeof params.damage !== 'number' || params.damage <= 0) return undefined;
    const base = params.damage;

    // A conditional bonus: a combo window, a target already afflicted, a target
    // of the right kind, or a target heavy enough to be worth pressing on.
    const conditional =
        params.empoweredDamage ?? params.escalationDamage ?? params.shatterBonus ?? params.smiteDamage ?? params.maxBonus;
    if (typeof conditional === 'number' && conditional > 0) {
        return `${round(base)}-${round(base + conditional)} ability damage (conditional)`;
    }

    // Venom banked on the target rather than the wielder: the ceiling is the
    // tier cap the sword's own passive declares.
    if (typeof params.damagePerTier === 'number' && params.damagePerTier > 0) {
        const tiers = maxVenomTiersFor(sword, params.venomEffect);
        return tiers === undefined
            ? `${round(base)}+ ability damage (scales with banked venom)`
            : `${round(base)}-${round(base + params.damagePerTier * tiers)} ability damage (scales with banked venom)`;
    }

    // A resource the wielder banks. The ceiling lives on whichever binding of
    // the same sword *fills* the meter, so look it up by shared charge key
    // rather than reporting only the empty-meter figure.
    if (typeof params.damagePerCharge === 'number') {
        const cap = maxChargesFor(sword, params.chargeKey);
        if (cap !== undefined) {
            return `${round(base)}-${round(base + params.damagePerCharge * cap)} ability damage (scales with banked charges)`;
        }
        return `${round(base)}+ ability damage (scales with banked charges)`;
    }
    if (typeof params.maxResonance === 'number' && params.maxResonance > 0) {
        return `${round(base)}-${round(base + params.maxResonance)} ability damage (scales with the crowd)`;
    }

    return `${round(base)} ability damage`;
}

/**
 * The charge ceiling a sword declares for one meter, read from whichever of its
 * bindings fills that meter.
 *
 * @param {any} sword
 * @param {string | undefined} chargeKey
 * @returns {number | undefined}
 */
function maxChargesFor(sword, chargeKey) {
    if (chargeKey === undefined) return undefined;
    for (const binding of sword?.abilities ?? []) {
        const params = binding.params ?? {};
        if (params.chargeKey === chargeKey && typeof params.maxCharges === 'number') return params.maxCharges;
    }
    return undefined;
}

/**
 * How many venom tiers a sword can build on one target, read from whichever of
 * its bindings does the building. Mirrors {@link maxChargesFor}, for the
 * resource that is banked on the enemy rather than on the wielder.
 *
 * @param {any} sword
 * @param {string | undefined} venomEffect
 * @returns {number | undefined}
 */
function maxVenomTiersFor(sword, venomEffect) {
    if (venomEffect === undefined) return undefined;
    for (const binding of sword?.abilities ?? []) {
        const params = binding.params ?? {};
        if (params.venomEffect === venomEffect && typeof params.maxAmplifier === 'number') {
            return params.maxAmplifier + 1;
        }
    }
    return undefined;
}
